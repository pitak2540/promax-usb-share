#!/usr/bin/env python3
"""Applies a brand (brands/<id>/) to the source tree before building.

    python3 tools/brand.py <id>

Writes common/.../Brand.java (read by the Windows program, the key generator and the phone app),
the icons and header images, and the few values that cannot come from Java (Android label and
application id, Inno Setup defines). Prints the brand's file base name for CI. Needs Pillow.
"""
import re
import sys
from pathlib import Path

from PIL import Image

root = Path(__file__).resolve().parent.parent
bid = sys.argv[1] if len(sys.argv) > 1 else "promax"
bdir = root / "brands" / bid
if not bdir.is_dir():
    sys.exit(f"no such brand: {bdir}")

props = {}
for line in (bdir / "brand.properties").read_text(encoding="utf-8").splitlines():
    line = line.strip()
    if line and not line.startswith("#") and "=" in line:
        k, v = line.split("=", 1)
        props[k.strip()] = v.strip()
need = ["name", "tagline", "short", "publisher", "file", "android.id", "prefs", "installer.id", "license.folder", "icon.bg"]
missing = [k for k in need if k not in props]
if missing:
    sys.exit(f"brand.properties missing: {missing}")


def jstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


(root / "common/src/com/james/usbshare/Brand.java").write_text(f'''package com.james.usbshare;

/** GENERATED by tools/brand.py from brands/{bid}/brand.properties — edit that file, not this one. */
public final class Brand {{
    private Brand() {{}}
    public static final String ID = {jstr(bid)};
    public static final String NAME = {jstr(props["name"])};
    public static final String TAGLINE = {jstr(props["tagline"])};
    public static final String SHORT = {jstr(props["short"])};
    public static final String FILE = {jstr(props["file"])};
    public static final String PREFS = {jstr(props["prefs"])};
    public static final String LICENSE_FOLDER = {jstr(props["license.folder"])};
}}
''', encoding="utf-8")


def sub(path, pattern, repl):
    p = root / path
    s = p.read_text(encoding="utf-8-sig")
    s2, n = re.subn(pattern, lambda m: repl, s, count=1)
    if n == 0:
        sys.exit(f"pattern not found in {path}: {pattern}")
    p.write_text(s2, encoding="utf-8")


sub("android/app/src/main/AndroidManifest.xml", r'android:label="[^"]*"',
    'android:label="' + props["name"].replace("&", "&amp;").replace('"', "&quot;") + '"')
sub("android/app/build.gradle", r"applicationId '[^']*'", "applicationId '" + props["android.id"] + "'")
sub("android/settings.gradle", r'rootProject.name = "[^"]*"', 'rootProject.name = "' + props["file"] + '"')

# Inno Setup: brand values as #defines at the top of setup.iss
iss = root / "installer/setup.iss"
s = iss.read_text(encoding="utf-8-sig")
body = "\n".join(l for l in s.splitlines() if not l.startswith("#define BRAND_") and not l.startswith("; BRAND"))
defs = ("; BRAND values written by tools/brand.py\n"
        f"#define BRAND_NAME {jstr(props['name'])}\n"
        f"#define BRAND_PUBLISHER {jstr(props['publisher'])}\n"
        f"#define BRAND_FILE {jstr(props['file'])}\n"
        f"#define BRAND_ID {jstr(props['installer.id'])}\n")
iss.write_bytes(b"\xef\xbb\xbf" + (defs + body + "\n").encode("utf-8"))

# images
fg = Image.open(bdir / "fg.png").convert("RGBA")
fg = fg.crop(fg.getbbox())
bg = tuple(bytes.fromhex(props["icon.bg"])) + (255,)


def fitted(box):
    im = fg.copy()
    im.thumbnail((box, box), Image.LANCZOS)
    return im


def square(size, background, scale):
    c = Image.new("RGBA", (size, size), background)
    im = fitted(int(size * scale))
    c.paste(im, ((size - im.width) // 2, (size - im.height) // 2), im)
    return c


res = root / "android/app/src/main/res"
for d, sz in [("mdpi", 108), ("hdpi", 162), ("xhdpi", 216), ("xxhdpi", 324), ("xxxhdpi", 432)]:
    (res / f"drawable-{d}").mkdir(parents=True, exist_ok=True)
    square(sz, (0, 0, 0, 0), 0.62).save(res / f"drawable-{d}/ic_launcher_logo.png")
(res / "drawable/ic_launcher_bg.xml").write_text(
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
    '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
    f'    <path android:fillColor="#FF{props["icon.bg"].upper()}" android:pathData="M0,0h108v108h-108z" />\n'
    '</vector>\n', encoding="utf-8")

header = fg.copy()
header.thumbnail((1024, 512), Image.LANCZOS)
(res / "drawable-nodpi").mkdir(parents=True, exist_ok=True)
for old in (res / "drawable-nodpi").glob("*_logo.png"):
    old.unlink()
header.save(res / "drawable-nodpi/brand_logo.png")
header.save(root / "desktop/resources/wordmark.png")
square(512, bg, 0.86).save(root / "desktop/resources/logo.png")
square(256, bg, 0.86).save(root / "desktop/icon.ico", sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])

print(props["file"])
